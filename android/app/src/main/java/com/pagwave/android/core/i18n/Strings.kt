enum class PagwaveLocale(val code: String, val nativeName: String, val isRtl: Boolean = false) {
    PT("pt", "Português"),
    EN("en", "English"),
    ES("es", "Español"),
    AR("ar", "العربية", isRtl = true),
    FR("fr", "Français"),
    DE("de", "Deutsch");

    companion object {
        fun fromCode(code: String?): PagwaveLocale =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: PT
    }
}

